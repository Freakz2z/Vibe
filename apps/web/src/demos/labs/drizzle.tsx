import { LabControls } from '../lab-kit';
import { apiUrl } from '../../lib/runtime';
import { useCallback, useEffect, useRef, useState } from 'react';
import type { DemoCopyHandler } from '../types';
import { Code, DataTable, ErrorNote, Lab, Select, Status, prettyJSON } from '../lab-kit';

interface DrizzleRow {
  orderId: string;
  customer: string;
  region: string;
  status: string;
  totalCents: number;
}

interface DrizzleResponse {
  technology: 'Drizzle ORM';
  sql: string;
  parameters: unknown[];
  rows: DrizzleRow[];
  source: string;
}

const REGIONS = ['all', '华东', '华南', '华北', '西部'] as const;
const STATUSES = ['all', 'paid', 'pending', 'refunded'] as const;

/**
 * Drizzle ORM: the SQL string and bound parameters come back from the server,
 * generated by a real relational query (join + optional filters). Showing that
 * generated SQL is the point of the ORM, so it is rendered verbatim.
 */
export default function DrizzleLab({ onCopy }: { onCopy: DemoCopyHandler }) {
  const [region, setRegion] = useState<string>('all');
  const [status, setStatus] = useState<string>('paid');
  const [data, setData] = useState<DrizzleResponse | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  const [nonce, setNonce] = useState(0);
  const controllerRef = useRef<AbortController | null>(null);

  const load = useCallback(async () => {
    controllerRef.current?.abort();
    const controller = new AbortController();
    controllerRef.current = controller;
    setPending(true);
    setError(null);
    // Old rows are cleared so a new filter can never be read against stale data.
    setData(null);
    try {
      const params = new URLSearchParams({ region, status });
      const response = await fetch(apiUrl(`/api/labs/drizzle?${params}`), { signal: controller.signal, cache: 'no-store' });
      if (!response.ok) throw new Error(`请求失败（HTTP ${response.status}）`);
      const payload = (await response.json()) as DrizzleResponse;
      if (controller.signal.aborted) return;
      setData(payload);
    } catch (err) {
      if (err instanceof DOMException && err.name === 'AbortError') return;
      if (controller.signal.aborted) return;
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      // Only the latest request may clear the pending flag.
      if (!controller.signal.aborted && controllerRef.current === controller) setPending(false);
    }
  }, [region, status, nonce]);

  useEffect(() => {
    void load();
    return () => controllerRef.current?.abort();
  }, [load]);

  const reset = useCallback(() => {
    controllerRef.current?.abort();
    setRegion('all');
    setStatus('paid');
    setNonce((n) => n + 1);
  }, []);

  const totalCents = data?.rows.reduce((sum, row) => sum + row.totalCents, 0) ?? 0;

  return (
    <Lab
      title="Drizzle ORM 关系查询"
      badge={<span className="demo-live-badge">Cloudflare D1</span>}
      reset={reset}
    >
      <div className="lab-layout">
        <LabControls className="lab-controls">
          <Select label="地区 region" value={region} options={REGIONS.map((r) => [r, r === 'all' ? '全部' : r])} onChange={setRegion} />
          <Select label="状态 status" value={status} options={STATUSES.map((s) => [s, s === 'all' ? '全部' : s])} onChange={setStatus} />
          <p className="lab-field__rule">
            订单与客户两张表由 Drizzle 的关系查询连接，可选条件会真正进入 SQL 的 WHERE 子句。结果为虚构示例订单。
          </p>
          {error ? <ErrorNote onRetry={() => void load()}>{error}</ErrorNote> : null}
        </LabControls>

        <div className="lab-stage">
          {pending ? <Status>查询中…</Status> : null}
          {data ? (
            <>
              <Status tone="ok">
                {data.technology} · 来源 {data.source} · 返回 {data.rows.length} 行 · 合计 {(totalCents / 100).toFixed(2)} 元（虚构示例订单）
              </Status>
              <DataTable
                head={['订单号', '客户', '地区', '状态', '金额（分）']}
                rows={data.rows.map((row) => [row.orderId, row.customer, row.region, row.status, row.totalCents.toLocaleString('zh-CN')])}
                caption="虚构示例订单数据，仅用于演示查询能力"
              />
            </>
          ) : pending ? null : (
            <Status>没有结果。</Status>
          )}
        </div>
      </div>

      {data ? (
        <>
          <Code
            text={`${data.sql}\n\n-- 绑定参数\n${prettyJSON(data.parameters)}`}
            onCopy={onCopy}
            label="Drizzle 生成的 SQL"
            maxHeight={260}
          />
          <Code text={prettyJSON(data.rows.slice(0, 5))} onCopy={onCopy} label="响应示例（前 5 行）" maxHeight={240} />
        </>
      ) : null}
    </Lab>
  );
}
