import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Content-derived so identical builds reuse caches; any deployed source/data/asset change busts them.
const hash = createHash('sha256');
function visit(directory: string) {
  for (const item of readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (['generated', 'node_modules', 'dist'].includes(item.name)) continue;
    const path = join(directory, item.name);
    if (item.isDirectory()) visit(path);
    else if (!path.endsWith('.tsbuildinfo')) {
      hash.update(path);
      hash.update(readFileSync(path));
    }
  }
}
for (const directory of ['src', 'shared', 'apps/web/src', 'apps/web/public', 'data', 'assets'])
  visit(directory);
for (const file of [
  'apps/web/index.html',
  'apps/web/package.json',
  'apps/web/vite.config.ts',
  'package.json',
  'package-lock.json',
  'wrangler.jsonc',
]) {
  hash.update(file);
  hash.update(readFileSync(file));
}
const revision = hash.digest('hex').slice(0, 20);
mkdirSync('shared/generated', { recursive: true });
writeFileSync(
  'shared/generated/build.ts',
  `// Generated by npm run build.\nexport const BUILD_REVISION = '${revision}';\n`,
);
console.log('Cache revision:', revision);
